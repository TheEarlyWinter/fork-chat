const MARKDOWN_MIME = 'text/markdown';
const ARTIFACT_FIELDS = [
  'artifactId', 'name', 'mime', 'format', 'bytes', 'sha256',
  'createdAt', 'cardId', 'requestId', 'preview', 'status', 'origin',
];

async function tempDataDir(t) {
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), 'fork-chat-artifacts-'));
  t.after(() => fs.rm(dir, { recursive: true, force: true }));
  return dir;
}

function makeRenderer({ delayMs = 0, html = '<p>安全预览</p>' } = {}) {
  const calls = [];
  const renderer = async (input, options = {}) => {
    calls.push(input);
    const signal = options?.signal || input?.signal;
    if (signal?.aborted) throw signal.reason || new DOMException('已取消', 'AbortError');
    if (delayMs) {
      await new Promise((resolve, reject) => {
        const timer = setTimeout(resolve, delayMs);
        const abort = () => {
          clearTimeout(timer);
          signal?.removeEventListener('abort', abort);
          reject(signal.reason || new DOMException('已取消', 'AbortError'));
        };
        signal?.addEventListener('abort', abort, { once: true });
      });
    }
    const bytes = Buffer.from(`generated:${input.content}`, 'utf8');
    return {
      bytes,
      name: input.name || input.filename,
      mime: input.mime || MARKDOWN_MIME,
      format: input.format || 'md',
      preview: String(input.content).slice(0, 800),
      previewHtml: html,
    };
  };
  renderer.calls = calls;
  return renderer;
}

function makeApp() {
  const routes = new Map();
  return {
    routes,
    post(route, handler) {
      routes.set(`POST ${route}`, handler);
    },
    get(route, handler) {
      routes.set(`GET ${route}`, handler);
    },
  };
}

function makeContext({ body = {}, appRequestContext } = {}) {
  return {
    req: {
      async json() { return body; },
    },
    get(key) {
      assert.equal(key, 'appRequestContext');
      return appRequestContext;
    },
    json(value, status = 200) {
      return Response.json(value, { status });
    },
  };
}

async function invoke(handler, context) {
  try {
    const response = await handler(context);
    const data = typeof response?.json === 'function' ? await response.json() : response;
    return { status: response?.status ?? 200, data };
  } catch (error) {
    return { status: error?.status || 500, error };
  }
}

async function walkRegularFiles(root) {
  const found = [];
  async function visit(current) {
    let entries;
    try {
      entries = await fs.readdir(current, { withFileTypes: true });
    } catch {
      return;
    }
    for (const entry of entries) {
      const full = path.join(current, entry.name);
      const stat = await fs.lstat(full);
      if (stat.isSymbolicLink()) continue;
      if (stat.isDirectory()) await visit(full);
      else if (stat.isFile()) found.push(full);
    }
  }
  await visit(root);
  return found;
}

async function findFileContaining(root, expected) {
  for (const file of await walkRegularFiles(root)) {
    const bytes = await fs.readFile(file);
    if (bytes.equals(expected)) return file;
  }
  return null;
}

function ownerContext(id, appId = 'fork-chat') {
  return { appId, principal: { kind: 'app', principalId: id } };
}

