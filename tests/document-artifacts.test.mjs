test('document-artifacts: manifest/bytes tamper, symlink replacement, and path traversal fail closed', async t => {
  const dataDir = await tempDataDir(t);
  const service = createArtifactService({ dataDir, renderer: makeRenderer() });
  const metadata = await service.create({
    owner: 'owner-a', cardId: 'card-a', requestId: 'req-manifest', filename: 'manifest.md', content: 'manifest',
  });
  const manifestFile = (await walkRegularFiles(dataDir)).find(file => path.basename(file) === 'manifest.json');
  assert.ok(manifestFile, 'the immutable record must have a manifest file');
  const manifest = JSON.parse(await fs.readFile(manifestFile, 'utf8'));
  manifest.metadata.name = 'attacker-controlled-name.md';
  await fs.writeFile(manifestFile, JSON.stringify(manifest));
  await assert.rejects(
    () => service.read({ owner: 'owner-a', artifactId: metadata.artifactId }),
    'metadata manifest tampering must be detected, not returned to the caller',
  );

  const bytesArtifact = await service.create({
    owner: 'owner-a', cardId: 'card-a', requestId: 'req-bytes', filename: 'tamper.md', content: 'original',
  });
  const originalBytes = Buffer.from('generated:original', 'utf8');
  const contentFile = await findFileContaining(dataDir, originalBytes);
  assert.ok(contentFile, 'the generated bytes must be persisted as a real file under dataDir');
  await fs.writeFile(contentFile, Buffer.from('tampered'));
  await assert.rejects(
    () => service.read({ owner: 'owner-a', artifactId: bytesArtifact.artifactId }),
    'hash mismatch must reject modified artifact bytes',
  );

  for (const artifactId of ['../etc/passwd', `../${metadata.artifactId}`, `${metadata.artifactId}/../x`, 'g'.repeat(32)]) {
    await assert.rejects(
      () => service.read({ owner: 'owner-a', artifactId }),
      `unsafe artifactId must not become a filesystem path: ${artifactId}`,
    );
  }

  const linked = await service.create({
    owner: 'owner-a', cardId: 'card-a', requestId: 'req-link', filename: 'linked.md', content: 'linked',
  });
  const linkedBytes = Buffer.from('generated:linked', 'utf8');
  const linkedFile = await findFileContaining(dataDir, linkedBytes);
  assert.ok(linkedFile);
  const outside = path.join(dataDir, 'outside-secret.txt');
  await fs.writeFile(outside, 'do-not-read');
  await fs.unlink(linkedFile);
  await fs.symlink(outside, linkedFile);
  await assert.rejects(
    () => service.read({ owner: 'owner-a', artifactId: linked.artifactId }),
    'symlink replacement must not be followed as an artifact',
  );
  assert.equal(await fs.readFile(outside, 'utf8'), 'do-not-read');
});

test('document-artifacts: renderer failure and abort leave no readable partial artifact', async t => {
  const dataDir = await tempDataDir(t);
  const failing = createArtifactService({
    dataDir,
    renderer: async () => { throw new Error('renderer failed'); },
  });
  await assert.rejects(
    () => failing.create({ owner: 'owner-a', cardId: 'card-a', requestId: 'req-fail', filename: 'fail.md', content: 'x' }),
    /renderer failed/,
  );

  const controller = new AbortController();
  let rendererSawSignal = false;
  const renderer = async (input, options = {}) => {
    const signal = options?.signal || input.signal;
    rendererSawSignal = Boolean(signal);
    await new Promise((resolve, reject) => {
      const timer = setTimeout(resolve, 40);
      signal?.addEventListener('abort', () => {
        clearTimeout(timer);
        reject(signal.reason || new DOMException('已取消', 'AbortError'));
      }, { once: true });
    });
    return { bytes: Buffer.from('late'), name: 'abort.md', mime: MARKDOWN_MIME, format: 'md', preview: 'late', previewHtml: '<p>late</p>' };
  };
  const service = createArtifactService({ dataDir, renderer });
  const filesBefore = (await walkRegularFiles(dataDir)).sort();
  const pending = service.create({ owner: 'owner-a', cardId: 'card-a', requestId: 'req-abort', filename: 'abort.md', content: 'x', signal: controller.signal });
  await new Promise(resolve => setImmediate(resolve));
  controller.abort(new DOMException('已取消', 'AbortError'));
  await assert.rejects(pending);
  assert.equal(rendererSawSignal, true, 'service.create must propagate signal to the renderer');
  const filesAfter = (await walkRegularFiles(dataDir)).sort();
  assert.deepEqual(filesAfter, filesBefore, 'aborted create must not leave an artifact file');
});

test('document-artifacts: owner identity comes only from appRequestContext, never caller headers or foreign app', () => {
  const context = {
    get(key) {
      assert.equal(key, 'appRequestContext');
      return ownerContext('real-owner');
    },
    req: { header: () => 'forged-owner' },
  };
  const owner = getArtifactOwner(context);
  context.req.header = () => 'different-forgery';
  assert.equal(getArtifactOwner(context), owner);
  const withSurfaceCredential = { get: () => ({ appId: 'fork-chat', principal: { kind: 'app', principalId: 'stable-principal', credentialId: 'surface-a' } }) };
  const withReopenedCredential = { get: () => ({ appId: 'fork-chat', principal: { kind: 'app', principalId: 'stable-principal', credentialId: 'surface-b' } }) };
  assert.equal(getArtifactOwner(withSurfaceCredential), getArtifactOwner(withReopenedCredential), 'principalId takes precedence over a changing credentialId when the host provides both');
  assert.notEqual(owner, getArtifactOwner({ get: () => ownerContext('other-owner') }));
  assert.throws(() => getArtifactOwner({ get: () => null }), err => err.code === 'ARTIFACT_FORBIDDEN');
  assert.throws(() => getArtifactOwner({ get: () => ownerContext('other-app', 'other-app') }), err => err.code === 'ARTIFACT_FORBIDDEN');
  assert.throws(() => getArtifactOwner({ get: () => ({ appId: 'fork-chat', principal: {} }) }), err => err.code === 'ARTIFACT_STABLE_ID_REQUIRED');
});

