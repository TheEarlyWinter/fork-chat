test('document-artifacts: register exposes only artifactId routes and enforces real owner context', async t => {
  const dataDir = await tempDataDir(t);
  const service = createArtifactService({ dataDir, renderer: makeRenderer({ html: '<p>route preview</p>' }) });
  const metadata = await service.create({
    owner: JSON.stringify(['fork-chat', 'app', 'owner-a']),
    cardId: 'card-a', requestId: 'req-a', filename: 'route.md', content: 'route body',
  });
  const app = makeApp();
  await service.register(app);
  assert.deepEqual([...app.routes.keys()].sort(), [
    'GET /api/artifacts/access-context',
    'POST /api/artifacts/export',
    'POST /api/artifacts/import',
    'POST /api/artifacts/preview',
  ]);

  const exportHandler = app.routes.get('POST /api/artifacts/export');
  const previewHandler = app.routes.get('POST /api/artifacts/preview');
  const trusted = ownerContext('owner-a');
  const exported = await invoke(exportHandler, makeContext({ body: { artifactId: metadata.artifactId }, appRequestContext: trusted }));
  assert.equal(exported.status, 200);
  assert.equal(exported.data.ok, true);
  assert.equal(exported.data.artifact.artifactId, metadata.artifactId);
  assert.equal(exported.data.contentBase64, Buffer.from('generated:route body', 'utf8').toString('base64'));

  const preview = await invoke(previewHandler, makeContext({ body: { artifactId: metadata.artifactId }, appRequestContext: trusted }));
  assert.equal(preview.status, 200);
  assert.equal(preview.data.ok, true);
  assert.equal(preview.data.html, '<p>route preview</p>');
  assert.equal(Object.hasOwn(preview.data, 'contentBase64'), false);

  for (const body of [
    {},
    { artifactId: metadata.artifactId, path: '/etc/passwd' },
    { artifactId: metadata.artifactId, owner: 'owner-a' },
  ]) {
    const result = await invoke(exportHandler, makeContext({ body, appRequestContext: trusted }));
    assert.ok(result.status >= 400, `route must reject non-contract body: ${JSON.stringify(body)}`);
  }

  for (const appRequestContext of [null, ownerContext('owner-a', 'other-app'), ownerContext('owner-b')]) {
    const result = await invoke(exportHandler, makeContext({ body: { artifactId: metadata.artifactId }, appRequestContext }));
    assert.ok(result.status >= 400, 'missing, foreign-app, and foreign-owner contexts must be rejected');
    assert.equal(result.data?.contentBase64, undefined);
  }
});

